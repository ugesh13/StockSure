-- StockSure schema. Rules live in the database so a bug in the API still cannot create negative stock.
-- Money is integer paise. Available stock = on_hand - reserved - buffer.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE branches (
  id                integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name              text        NOT NULL,
  city              text        NOT NULL,            -- powers the OpenSearch city filter
  last_heartbeat_at timestamptz NOT NULL DEFAULT now() -- last time the branch confirmed its stock (freshness rule)
);

CREATE TABLE products (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  sku         text    NOT NULL UNIQUE,
  name        text    NOT NULL,
  brand       text    NOT NULL,
  category    text    NOT NULL,
  tags        text[]  NOT NULL DEFAULT '{}',
  price_paise integer NOT NULL CHECK (price_paise > 0),
  image_url   text
);
CREATE INDEX products_category_idx   ON products (category);
CREATE INDEX products_name_trgm_idx  ON products USING gin (name  gin_trgm_ops);
CREATE INDEX products_brand_trgm_idx ON products USING gin (brand gin_trgm_ops);

CREATE TABLE customers (
  id    integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name  text NOT NULL,
  email text NOT NULL UNIQUE,
  phone text
);

CREATE TABLE inventory (
  branch_id  integer NOT NULL REFERENCES branches (id),
  product_id integer NOT NULL REFERENCES products (id),
  on_hand    integer NOT NULL CHECK (on_hand  >= 0),
  reserved   integer NOT NULL DEFAULT 0 CHECK (reserved >= 0),
  buffer     integer NOT NULL DEFAULT 0 CHECK (buffer   >= 0),
  rev        bigint  NOT NULL DEFAULT 0,               -- +1 on every change (used by search sync)
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (branch_id, product_id)
);
CREATE INDEX inventory_product_idx ON inventory (product_id);

CREATE TABLE carts (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  customer_id integer NOT NULL UNIQUE REFERENCES customers (id),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE cart_items (
  cart_id    integer NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES products (id),
  branch_id  integer NOT NULL REFERENCES branches (id),
  qty        integer NOT NULL CHECK (qty BETWEEN 1 AND 10),
  PRIMARY KEY (cart_id, product_id, branch_id)
);

CREATE TYPE order_status AS ENUM ('AWAITING_PAYMENT', 'PLACED', 'EXPIRED', 'CANCELLED', 'NEEDS_RESCUE');

CREATE TABLE orders (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id     integer      NOT NULL REFERENCES customers (id),
  status          order_status NOT NULL,
  total_paise     bigint       NOT NULL CHECK (total_paise >= 0),
  fulfilment      text         NOT NULL CHECK (fulfilment IN ('PICKUP', 'DELIVERY')),
  idempotency_key text         NOT NULL,
  expires_at      timestamptz,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  paid_at         timestamptz,
  finalized_at    timestamptz,                          -- set once by the inventory-finalizer consumer
  UNIQUE (customer_id, idempotency_key)
);
CREATE INDEX orders_pending_idx  ON orders (expires_at) WHERE status = 'AWAITING_PAYMENT';
CREATE INDEX orders_customer_idx ON orders (customer_id, created_at DESC);

CREATE TABLE order_lines (
  order_id         uuid    NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id       integer NOT NULL REFERENCES products (id),
  branch_id        integer NOT NULL REFERENCES branches (id),
  qty              integer NOT NULL CHECK (qty BETWEEN 1 AND 10),
  unit_price_paise integer NOT NULL CHECK (unit_price_paise > 0),   -- price snapshot
  PRIMARY KEY (order_id, product_id, branch_id)
);
CREATE INDEX order_lines_stock_idx ON order_lines (branch_id, product_id);

-- The one ledger: online holds, online sales, POS sales, staff counts, releases, restocks.
CREATE TABLE stock_ledger (
  id             bigserial PRIMARY KEY,
  branch_id      integer NOT NULL REFERENCES branches (id),
  product_id     integer NOT NULL REFERENCES products (id),
  kind           text    NOT NULL CHECK (kind IN ('HOLD', 'RELEASE', 'ONLINE_SALE', 'POS_SALE', 'STAFF_COUNT', 'RESTOCK')),
  delta_on_hand  integer NOT NULL DEFAULT 0,
  delta_reserved integer NOT NULL DEFAULT 0,
  ref            text,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX stock_ledger_item_idx ON stock_ledger (branch_id, product_id, id);

-- Transactional outbox: the event is saved in the same transaction as the change; the relay publishes it later.
CREATE TABLE outbox (
  id              bigserial PRIMARY KEY,
  topic           text  NOT NULL CHECK (topic IN ('orders', 'inventory')),
  key             text  NOT NULL,
  payload         jsonb NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  published_at    timestamptz,
  kafka_partition integer,
  kafka_offset    bigint,
  attempts        integer NOT NULL DEFAULT 0
);
CREATE INDEX outbox_pending ON outbox (id) WHERE published_at IS NULL;

-- Stops a duplicate event from being applied twice.
CREATE TABLE processed_events (
  consumer     text NOT NULL,
  event_id     uuid NOT NULL,
  processed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (consumer, event_id)
);

CREATE TABLE notifications (
  id         bigserial PRIMARY KEY,
  order_id   uuid NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  type       text NOT NULL,
  status     text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, type)
);

CREATE TABLE stock_alerts (
  id          bigserial PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers (id),
  product_id  integer NOT NULL REFERENCES products (id),
  branch_id   integer NOT NULL REFERENCES branches (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  notified_at timestamptz,
  UNIQUE (customer_id, product_id, branch_id)
);
CREATE INDEX stock_alerts_waiting_idx ON stock_alerts (product_id, branch_id) WHERE notified_at IS NULL;
